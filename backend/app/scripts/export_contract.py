"""Write the SSE contract shape to `shared/`.

    uv run python -m app.scripts.export_contract

The committed JSON is what the frontend's contract test compares against, so
the TypeScript side needs no Python to run its own test — which matters because
`pnpm test` has to pass without a Python environment.

Run this after changing `app/api/events.py`. A test fails if you forget.
"""

import json
from pathlib import Path

from app.api.events import contract_shape

# backend/app/scripts/export_contract.py -> backend/app/scripts -> ... -> repo
CONTRACT_PATH = Path(__file__).resolve().parents[3] / "shared" / "stream-events.contract.json"

HEADER = (
    "Generated by `uv run python -m app.scripts.export_contract`. "
    "Do not edit by hand; edit backend/app/api/events.py and regenerate."
)


def render() -> str:
    """The contract as formatted JSON, with a trailing newline."""
    return json.dumps({"_generated": HEADER, "events": contract_shape()}, indent=2) + "\n"


def main() -> None:
    CONTRACT_PATH.write_text(render(), encoding="utf-8")
    print(f"wrote {CONTRACT_PATH.relative_to(CONTRACT_PATH.parents[1])}")


if __name__ == "__main__":
    main()
